// Generates docs/scenarios.md from the scenario registry in the built core
// package, so the documentation can never drift from the code.
//   node scripts/generate-scenario-docs.mjs          write the file
//   node scripts/generate-scenario-docs.mjs --check  fail if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listScenarios, resolveScenario } from '@workfonic/mockclock';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs', 'scenarios.md');
const fmt = (v) => (Array.isArray(v) ? (v.length ? v.join(', ') : '(none)') : String(v));
const esc = (s) => s.replace(/\|/g, '\\|');

let out = `# Scenarios

<!-- Generated by scripts/generate-scenario-docs.mjs from packages/core/src/scenarios.ts. Do not edit by hand. -->

A scenario is a named, configurable starting point for a time-sensitive test. Every scenario, its parameters and their defaults are defined once, in the registry in [\`packages/core/src/scenarios.ts\`](../packages/core/src/scenarios.ts). This page is generated from it.

\`\`\`ts
import { MockClock, resolveScenario } from '@workfonic/mockclock';

const clock = MockClock.scenario('payroll', { year: 2027, month: 1 }); // frozen at the scenario start
clock.scenario?.events;                                               // key instants, sorted
const resolved = resolveScenario('payroll', { year: 2027, month: 1 }); // the same data without a clock
\`\`\`

- A scenario clock is **frozen** at \`start\` and uses the scenario's time zone for calendar arithmetic.
- Parameters may be passed typed (\`{ month: 2 }\`) or as strings (\`{ month: '2' }\`, as the CLI does). Lists accept arrays or comma-separated strings.
- Unknown parameters, out-of-range values, invalid dates and invalid time zones throw \`InvalidScenarioParameterError\`.
- \`leadSeconds\` controls how long before the key moment the clock starts.
- MockClock ships **no public-holiday data**. Holiday parameters default to example dates only.

CLI: \`mockclock scenarios\` lists them; \`mockclock scenario <id> -p key=value\` resolves one.

`;

for (const s of listScenarios()) {
  const r = resolveScenario(s.id);
  out += `## \`${s.id}\`: ${s.title}\n\n${s.description}\n\nCategory: ${s.category}\n\n`;
  out += `| Parameter | Type | Default | Description |\n|---|---|---|---|\n`;
  for (const [k, spec] of Object.entries(s.params)) {
    const range = spec.min !== undefined || spec.max !== undefined ? ` (${spec.min ?? ''}..${spec.max ?? ''})` : '';
    const values = spec.values ? ` (${spec.values.join(' / ')})` : '';
    out += `| \`${k}\` | ${spec.type}${range}${values} | \`${esc(fmt(spec.default))}\` | ${esc(spec.description)} |\n`;
  }
  out += `\nWith defaults: starts at \`${r.startLocal}\` (${r.timeZone}).\n\n| Event | Local time |\n|---|---|\n`;
  for (const e of r.events) out += `| ${esc(e.label)} (\`${e.id}\`) | \`${e.local}\` |\n`;
  if (r.notes.length) out += `\n${r.notes.map((n) => `> ${n}`).join('\n>\n')}\n`;
  out += '\n';
}

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== out) {
    console.error('docs/scenarios.md is out of date. Run: node scripts/generate-scenario-docs.mjs');
    process.exit(1);
  }
  console.log('docs/scenarios.md is up to date.');
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${path.relative(root, target)}`);
}
